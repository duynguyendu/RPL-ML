from __future__ import annotations

import shutil
import subprocess
import tempfile
from pathlib import Path

import emlearn
import joblib
import m2cgen
from emlearn.trees import SUPPORTED_ESTIMATORS as EMLEARN_SUPPORTED_ESTIMATORS


def convert_to_c(
    model_path: str | Path, out_dir: str | Path, func_name: str = "mlof_predict_pdr"
) -> tuple[Path, Path]:
    model = joblib.load(model_path)
    feature_names = [str(name) for name in model.feature_names_in_]
    source_body = m2cgen.export_to_c(model, function_name=func_name)

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    c_path = out_dir / f"{func_name}.c"
    h_path = out_dir / f"{func_name}.h"

    header_guard = f"{func_name.upper()}_H_"
    header = f"""\
/* Auto-generated by scripts/models/to_c.py (via m2cgen) from a trained
 * model. DO NOT EDIT BY HAND -- retrain and re-run the converter
 * instead.
 *
 * input[] must hold these features, in this order:
 *   {", ".join(f"{i}: {name}" for i, name in enumerate(feature_names))}
 */
#ifndef {header_guard}
#define {header_guard}

double {func_name}(double *input);

#endif /* {header_guard} */
"""
    source = (
        "/* Auto-generated by scripts/models/to_c.py (via m2cgen) from a "
        "trained model.\n"
        " * DO NOT EDIT BY HAND -- retrain and re-run the converter "
        "instead. */\n"
        f'#include "{func_name}.h"\n\n' + source_body
    )

    c_path.write_text(source)
    h_path.write_text(header)
    return c_path, h_path


def convert_to_c_emlearn(
    model_path: str | Path, out_dir: str | Path, func_name: str = "mlof_predict_pdr"
) -> tuple[Path, Path] | None:
    model = joblib.load(model_path)
    if type(model).__name__ not in EMLEARN_SUPPORTED_ESTIMATORS:
        return None

    feature_names = [str(name) for name in model.feature_names_in_]
    cmodel = emlearn.convert(model, method="inline", dtype="float")
    source_body = cmodel.save(name=func_name, format="c")

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    c_path = out_dir / f"{func_name}.c"
    h_path = out_dir / f"{func_name}.h"

    header_guard = f"{func_name.upper()}_H_"
    header = f"""\
/* Auto-generated by scripts/models/to_c.py (via emlearn) from a trained
 * model. DO NOT EDIT BY HAND -- retrain and re-run the converter
 * instead.
 *
 * features[] must hold these, in this order:
 *   {", ".join(f"{i}: {name}" for i, name in enumerate(feature_names))}
 */
#ifndef {header_guard}
#define {header_guard}
#include <stdint.h>

float {func_name}_predict(const float *features, int32_t features_length);

#endif /* {header_guard} */
"""
    source = (
        "/* Auto-generated by scripts/models/to_c.py (via emlearn) from a "
        "trained model.\n"
        " * DO NOT EDIT BY HAND -- retrain and re-run the converter "
        "instead. */\n"
        f'#include "{func_name}.h"\n\n' + source_body
    )

    c_path.write_text(source)
    h_path.write_text(header)
    return c_path, h_path


def measure_size(c_path: str | Path, mcu: str = "msp430f2617") -> str | None:
    gcc = shutil.which("msp430-gcc")
    size_tool = shutil.which("msp430-size")
    if gcc is None or size_tool is None:
        print("msp430-gcc/msp430-size not found -- skipping size measurement.")
        return None

    c_path = Path(c_path)
    with tempfile.TemporaryDirectory() as tmp:
        o_path = Path(tmp) / (c_path.stem + ".o")
        result = subprocess.run(
            [
                gcc,
                f"-mmcu={mcu}",
                "-Os",
                "-I",
                str(c_path.parent),
                "-c",
                str(c_path),
                "-o",
                str(o_path),
            ],
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            print("msp430-gcc FAILED to compile:\n" + result.stderr)
            return None

        size_result = subprocess.run(
            [size_tool, str(o_path)], capture_output=True, text=True
        )
        print(size_result.stdout)
        return size_result.stdout
